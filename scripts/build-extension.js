import {fileURLToPath} from 'node:url';
import {build} from 'esbuild';

// `gh extension install` clones the repository without running npm install,
// so the extension runs this committed bundle with its dependencies inlined.
// CI rebuilds it and fails if the committed copy differs from the source.
await build({
  entryPoints: [fileURLToPath(new URL('../bin/gh-pr-check-explainer.js', import.meta.url))],
  outfile: fileURLToPath(new URL('../dist/gh-pr-check-explainer.mjs', import.meta.url)),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  legalComments: 'none',
  // yaml resolves to its CommonJS build, which requires Node built-ins.
  banner: {js: [
    '// Generated by scripts/build-extension.js. Do not edit. Bundled dependency licenses: THIRD_PARTY_NOTICES.md',
    "import {createRequire} from 'node:module';",
    'const require = createRequire(import.meta.url);'
  ].join('\n')}
});
console.log('gh extension bundle: dist/gh-pr-check-explainer.mjs');
