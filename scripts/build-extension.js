import {fileURLToPath} from 'node:url';
import {build} from 'esbuild';

// `gh extension install` clones the repository without running npm install,
// and GitHub Actions runs an action's files as committed, so both run these
// bundles with their dependencies inlined. CI rebuilds them and fails if the
// committed copies differ from the source.
const bundles = [
  ['../bin/gh-pr-check-explainer.js', '../dist/gh-pr-check-explainer.mjs', 'gh extension'],
  ['../src/action-main.js', '../dist/action.mjs', 'GitHub Action']
];
for (const [entry, output, label] of bundles) {
  await build({
    entryPoints: [fileURLToPath(new URL(entry, import.meta.url))],
    outfile: fileURLToPath(new URL(output, import.meta.url)),
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node22',
    legalComments: 'none',
    // yaml resolves to its CommonJS build, which requires Node built-ins.
    banner: {js: [
      '// Generated by scripts/build-extension.js. Do not edit. Bundled dependency licenses: THIRD_PARTY_NOTICES.md',
      "import {createRequire} from 'node:module';",
      'const require = createRequire(import.meta.url);'
    ].join('\n')}
  });
  console.log(label + ' bundle: ' + output.slice(3));
}
